"""File storage, behind an interface.

Right now files go to a folder on this machine. Later they go to DigitalOcean
Spaces. Nothing outside this file needs to know which — the rest of the code
just calls `get_storage()`.
"""

from __future__ import annotations

import shutil
import uuid
from abc import ABC, abstractmethod
from pathlib import Path
from typing import BinaryIO

from app.config import PROJECT_ROOT, settings


class Storage(ABC):
    """What every storage backend must be able to do."""

    @abstractmethod
    def save(self, data: BinaryIO, original_filename: str, folder: str) -> str:
        """Store the file and return the key needed to find it again."""

    @abstractmethod
    def open(self, key: str) -> BinaryIO:
        """Open a stored file for reading."""

    @abstractmethod
    def delete(self, key: str) -> None:
        """Remove a stored file."""

    @abstractmethod
    def exists(self, key: str) -> bool: ...


class LocalStorage(Storage):
    """Files on disk, under ./storage. Used during development."""

    def __init__(self, root: Path | None = None) -> None:
        configured = Path(settings.local_storage_path)
        if root is not None:
            self.root = root
        elif configured.is_absolute():
            self.root = configured
        else:
            self.root = PROJECT_ROOT / configured
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        # Keys are generated by us, but never let one escape the storage root.
        candidate = (self.root / key).resolve()
        if not candidate.is_relative_to(self.root.resolve()):
            raise ValueError(f"Refusing to touch a file outside storage: {key}")
        return candidate

    def save(self, data: BinaryIO, original_filename: str, folder: str) -> str:
        suffix = Path(original_filename).suffix.lower()
        key = f"{folder}/{uuid.uuid4().hex}{suffix}"
        destination = self._path(key)
        destination.parent.mkdir(parents=True, exist_ok=True)
        with destination.open("wb") as out:
            shutil.copyfileobj(data, out)
        return key

    def open(self, key: str) -> BinaryIO:
        return self._path(key).open("rb")

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()


class S3Storage(Storage):
    """Blob storage (DigitalOcean Spaces, or any S3-compatible store). NOT BUILT YET.

    The settings it will need are already read from .env (S3_ENDPOINT_URL,
    S3_BUCKET, S3_ACCESS_KEY, S3_SECRET_KEY, S3_REGION). To finish it: add
    boto3, then save = put_object, open = get_object, delete = delete_object,
    exists = head_object, using the same "folder/uuid.ext" keys as LocalStorage
    so files can be copied across unchanged.
    """

    def __init__(self) -> None:
        missing = [
            name
            for name, value in (
                ("S3_ENDPOINT_URL", settings.s3_endpoint_url),
                ("S3_BUCKET", settings.s3_bucket),
                ("S3_ACCESS_KEY", settings.s3_access_key),
                ("S3_SECRET_KEY", settings.s3_secret_key),
            )
            if not value
        ]
        hint = f" Missing in .env: {', '.join(missing)}." if missing else ""
        raise NotImplementedError(
            "Blob storage is not connected yet." + hint
            + " Use STORAGE_PROVIDER=local for now."
        )

    def save(self, data: BinaryIO, original_filename: str, folder: str) -> str:
        raise NotImplementedError

    def open(self, key: str) -> BinaryIO:
        raise NotImplementedError

    def delete(self, key: str) -> None:
        raise NotImplementedError

    def exists(self, key: str) -> bool:
        raise NotImplementedError


def get_storage() -> Storage:
    """Pick the backend named in the environment."""
    if settings.storage_provider == "local":
        return LocalStorage()
    if settings.storage_provider == "s3":
        return S3Storage()
    raise NotImplementedError(
        f"Storage provider '{settings.storage_provider}' is not built yet. "
        "Set STORAGE_PROVIDER=local in your .env."
    )
